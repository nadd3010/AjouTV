`timescale 1ns / 1ps

module tb_softmax_lut;

    // --------------------------------------------------------
    // 1. 입출력 신호 선언
    // DUT의 포트 선언에 맞춰 signed를 빼고 unsigned(기본값)로 통일합니다.
    // --------------------------------------------------------
    reg                clk;
    reg                rst_n;
    reg                start;
    reg  signed [15:0] score [0:3][0:3];       // ✅ signed 추가
    wire signed [15:0] attn_weight [0:3][0:3]; // ✅ signed 추가
    wire               done;

    // --------------------------------------------------------
    // 2. DUT (Device Under Test) 연결
    // --------------------------------------------------------
    softmax_lut dut (
        .clk(clk),
        .rst_n(rst_n),
        .start(start),
        .score(score),
        .attn_weight(attn_weight),
        .done(done)
    );

    // --------------------------------------------------------
    // 3. 클럭 생성 (100MHz)
    // --------------------------------------------------------
    always #5 clk = ~clk;

    // --------------------------------------------------------
    // 4. 테스트 시나리오
    // --------------------------------------------------------
    integer i, j;

    initial begin
        // 초기화
        clk = 0;
        rst_n = 0;
        start = 0;

        // X(Unknown) 값 전파 방지: 입력 배열 전체를 0으로 깨끗하게 밀어줍니다.
        for (i = 0; i < 4; i = i + 1) begin
            for (j = 0; j < 4; j = j + 1) begin
                score[i][j] = 16'h0000;
            end
        end

        #20 rst_n = 1; // 리셋 해제

        // ----------------------------------------------------
        // 테스트 데이터 주입 (Clipping 및 Slicing 동작 확인)
        // ----------------------------------------------------
        
        // [테스트 1] 정상 슬라이싱 확인 (SLICE_START = 4 기준)
        // 16'h0010 (십진수 16) -> 우측으로 4번 시프트하면 1번지 인덱스 매핑 예상
        score[0][0] = 16'h0010;

        // [테스트 2] 음수 Clipping (최소치 고정) 확인
        // 16'hFFFF (십진수 -1) -> 음수이므로 0번지 인덱스로 제한되어야 함
        score[0][1] = 16'hFFFF;

        // [테스트 3] 최대치 Clipping 확인
        // 16'h7FFF (매우 큰 양수) -> 유효 범위를 초과하므로 255번지 인덱스로 제한되어야 함
        score[1][0] = 16'h7FFF;

        #10 start = 1; // 연산 시작
        #10 start = 0;

        // ----------------------------------------------------
        // 5. 무한 루프 방지용 타임아웃 대기 (fork ... join_any)
        // ----------------------------------------------------
        fork
            begin
                wait(done);
                #20 $display("Softmax LUT 계산 완료! 파형 창에서 결과를 확인하세요.");
                $stop; // 시뮬레이터 창이 꺼지지 않도록 $stop 사용
            end
            begin
                $display("에러: 타임아웃 발생! 상태 머신이 멈췄습니다.");
                $stop;
            end
        join_any
    end

endmodule